package com.github.kamiazya.graphviz.type

/**
 * A type alias representing the value of an attribute.
 *
 * The `AttributeValue` type can represent any kind of attribute value within the graph structure.
 * It serves as a flexible representation for attribute values, enabling compatibility with various
 * types such as strings, numbers, or other objects.
 */
typealias AttributeValue = Any
